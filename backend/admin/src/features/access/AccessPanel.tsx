import { useId, type FormEvent } from 'react';
import type { AdminConfiguration } from '../../shared/config.ts';
import type { useOperatorAccess } from './useOperatorAccess.ts';

type Props = {
  identity: AdminConfiguration['identity'];
  flow: ReturnType<typeof useOperatorAccess>;
};

export function AccessPanel({ identity, flow }: Props) {
  const { state, busy, error } = flow;
  const messageId = useId();
  const headingId = useId();

  function submitCredentials(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const fields = new FormData(event.currentTarget);
    if (identity.kind === 'local') {
      const token = String(fields.get('token') ?? '').trim();
      event.currentTarget.reset();
      if (token) void flow.signInLocal(token);
      return;
    }
    const email = String(fields.get('email') ?? '').trim();
    const password = String(fields.get('password') ?? '');
    const input = event.currentTarget.elements.namedItem('password');
    if (input instanceof HTMLInputElement) input.value = '';
    if (email && password) void flow.signIn(email, password);
  }

  function submitFactor(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const fields = new FormData(event.currentTarget);
    const factor = String(fields.get('factor') ?? '');
    const code = String(fields.get('code') ?? '').trim();
    const input = event.currentTarget.elements.namedItem('code');
    if (input instanceof HTMLInputElement) input.value = '';
    if (factor && /^\d{6}$/.test(code)) void flow.verify(factor, code);
  }

  return (
    <section className="surface" aria-labelledby={headingId}>
      <div className="panel-title">
        <span className="panel-icon" aria-hidden="true">{state.kind === 'operator' ? '✓' : '↳'}</span>
        <h2 id={headingId}>Operator access</h2>
      </div>

      {identity.kind === 'unavailable' ? (
        <div className="state">
          <p className="state-title">Setup required</p>
          <p>{identity.reason}</p>
        </div>
      ) : state.kind === 'signed-out' ? (
        <form onSubmit={submitCredentials} aria-describedby={error ? messageId : undefined}>
          {identity.kind === 'local' ? (
            <label>
              Local operator credential
              <input name="token" type="password" required maxLength={8192} autoComplete="off" autoCapitalize="off" spellCheck={false} />
              <span className="field-help">Use the credential generated by the local development harness.</span>
            </label>
          ) : (
            <>
              <label>Work email<input name="email" type="email" required autoComplete="username" maxLength={320} /></label>
              <label>Password<input name="password" type="password" required autoComplete="current-password" /></label>
            </>
          )}
          <button className="primary" type="submit" disabled={busy}>{busy ? 'Signing in…' : 'Sign in'}</button>
        </form>
      ) : state.kind === 'challenge' ? (
        <form onSubmit={submitFactor} aria-describedby={error ? messageId : undefined}>
          <p>Enter the six-digit code from your authenticator app.</p>
          <label>
            Authenticator
            <select name="factor">
              {state.factors.map((factor) => <option value={factor.id} key={factor.id}>{factor.label}</option>)}
            </select>
          </label>
          <label>Verification code<input name="code" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6} required /></label>
          <div className="button-row">
            <button className="primary" type="submit" disabled={busy}>{busy ? 'Verifying…' : 'Verify'}</button>
            <button type="button" onClick={() => void flow.signOut()}>Cancel</button>
          </div>
        </form>
      ) : state.kind === 'checking' ? (
        <p role="status">Checking permissions…</p>
      ) : state.kind === 'operator' ? (
        <div className="state">
          <p className="state-title access-ok">Operator role verified</p>
          <p>Verified at <LocalTime iso={state.verifiedAt} />.</p>
          <div className="button-row">
            <button type="button" onClick={() => void flow.retryAccess()} disabled={busy}>Recheck access</button>
            <button type="button" onClick={() => void flow.signOut()}>Sign out</button>
          </div>
        </div>
      ) : (
        <div className="state">
          {state.kind === 'denied' ? (
            <>
              <p className="state-title">Operator access denied</p>
              <p>Ask your Levelmaxing administrator to confirm your operator role.</p>
            </>
          ) : state.kind === 'enrollment-required' ? (
            <>
              <p className="state-title">Authenticator enrollment required</p>
              <p>Enroll a TOTP authenticator through your administrator before signing in here.</p>
            </>
          ) : (
            <>
              <p className="state-title">Permissions could not be checked</p>
              <p>Verify that the API is reachable and retry the check.</p>
            </>
          )}
          <div className="button-row">
            {state.kind === 'unavailable' && (
              <button className="primary" type="button" onClick={() => void flow.retryAccess()} disabled={busy}>Retry access check</button>
            )}
            <button type="button" onClick={() => void flow.signOut()}>Sign out</button>
          </div>
        </div>
      )}

      {error && <p className="error" id={messageId} role="alert">{error}</p>}
    </section>
  );
}

function LocalTime({ iso }: { iso: string }) {
  return <time dateTime={iso}>{new Intl.DateTimeFormat(undefined, { timeStyle: 'medium' }).format(new Date(iso))}</time>;
}
